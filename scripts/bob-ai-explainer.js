/**
 * Bob AI-Powered Patch Explainer
 * Uses Bob CLI to generate intelligent commit explanations
 */

const { execSync } = require('child_process');
const fs = require('fs');

class BobAIExplainer {
  constructor(config) {
    this.config = config;
    this.useBobCLI = this.checkBobCLI();
  }

  /**
   * Check if Bob CLI is available
   */
  checkBobCLI() {
    try {
      execSync('bob --version', { stdio: 'pipe' });
      return true;
    } catch (error) {
      console.warn('⚠️  Bob CLI not available, using rule-based analysis');
      return false;
    }
  }

  /**
   * Generate explanation using Bob CLI
   */
  async explainWithBob(diff, files, commitMessage) {
    if (!this.useBobCLI) {
      throw new Error('Bob CLI not available');
    }

    try {
      console.log('🤖 Asking Bob AI to analyze the patch...');

      // Create the prompt for Bob
      const prompt = this.createAnalysisPrompt(diff, files, commitMessage);
      
      // Write prompt to temp file to avoid shell escaping issues
      const tempFile = `/tmp/bob-prompt-${Date.now()}.txt`;
      fs.writeFileSync(tempFile, prompt);

      // Call Bob CLI with simpler approach - use text output instead of JSON
      const bobCommand = process.env.BOB_AUTH_METHOD
        ? `bob --auth-method ${process.env.BOB_AUTH_METHOD} --chat-mode ask --hide-intermediary-output`
        : `bob --chat-mode ask --hide-intermediary-output`;
      
      const result = execSync(
        `cat ${tempFile} | ${bobCommand}`,
        {
          encoding: 'utf8',
          maxBuffer: 10 * 1024 * 1024, // 10MB buffer
          timeout: 30000 // 30 second timeout
        }
      );

      // Clean up temp file
      try { fs.unlinkSync(tempFile); } catch (e) {}

      // Parse Bob's response
      const response = result.trim();
      
      // If Bob returned empty response, throw error
      if (!response || response.length < 10) {
        throw new Error('Bob returned empty or very short response');
      }
      
      return this.formatBobExplanation(response);

    } catch (error) {
      console.error('❌ Bob CLI failed:', error.message);
      throw error; // Re-throw to let caller handle
    }
  }

  /**
   * Create analysis prompt for Bob
   */
  createAnalysisPrompt(diff, files, commitMessage) {
    return `Analyze this git commit and provide a concise explanation in markdown format.

COMMIT MESSAGE:
${commitMessage}

FILES CHANGED (${files.length}):
${files.map(f => `- ${f.filename} (+${f.additions || 0}/-${f.deletions || 0})`).join('\n')}

DIFF:
\`\`\`diff
${diff.substring(0, 5000)}${diff.length > 5000 ? '\n... (truncated)' : ''}
\`\`\`

Please provide:
1. A brief summary of what this commit does (2-3 sentences)
2. Key changes made (bullet points)
3. Impact assessment (risk level: low/medium/high, testing status)

Format your response as markdown. Be concise and technical.`;
  }

  /**
   * Parse Bob's JSON response
   */
  parseBobResponse(jsonOutput) {
    try {
      // Bob CLI returns JSON with the response
      const parsed = JSON.parse(jsonOutput);
      
      // Extract the actual response text
      // Bob CLI format: { response: "...", stats: {...} }
      if (parsed.response && parsed.response.trim()) {
        return parsed.response;
      } else if (parsed.result && parsed.result.trim()) {
        return parsed.result;
      } else if (typeof parsed === 'string' && parsed.trim()) {
        return parsed;
      }
      
      // If response is empty, Bob might have returned stats only
      console.warn('⚠️  Bob returned empty response, using fallback');
      return null;
    } catch (error) {
      // If JSON parsing fails, try to extract text
      console.warn('⚠️  Failed to parse Bob JSON:', error.message);
      return null;
    }
  }

  /**
   * Format Bob's explanation into our standard format
   */
  formatBobExplanation(bobResponse) {
    return `## 🤖 AI Analysis by Bob

${bobResponse}

---
*Generated by Bob AI*`;
  }

  /**
   * Fallback to rule-based analysis if Bob CLI fails
   */
  fallbackExplanation(diff, files) {
    const analysis = this.analyzePatterns(diff, files);
    
    return `## 📝 Code Analysis

**Type:** ${analysis.type}
**Scope:** ${files.length} file${files.length > 1 ? 's' : ''} modified
**Size:** ${analysis.size} change (+${analysis.additions}/-${analysis.deletions} lines)

**Key Changes:**
${analysis.keyChanges.map(c => `- ${c}`).join('\n')}

**Impact:**
- **Risk Level:** ${analysis.risk}
- **Testing:** ${analysis.testing}

---
*Rule-based analysis (Bob CLI not available)*`;
  }

  /**
   * Simple pattern-based analysis for fallback
   */
  analyzePatterns(diff, files) {
    const additions = files.reduce((sum, f) => sum + (f.additions || 0), 0);
    const deletions = files.reduce((sum, f) => sum + (f.deletions || 0), 0);
    
    let type = 'Code modification';
    if (additions > deletions * 3) type = 'New feature';
    else if (deletions > additions * 3) type = 'Code cleanup';
    
    let size = 'Small';
    const total = additions + deletions;
    if (total > 200) size = 'Large';
    else if (total > 50) size = 'Medium';
    
    const keyChanges = [];
    if (diff.includes('function') || diff.includes('def ')) {
      keyChanges.push('New functions added');
    }
    if (diff.includes('test') || diff.includes('spec')) {
      keyChanges.push('Tests updated');
    }
    if (diff.includes('import') || diff.includes('require')) {
      keyChanges.push('Dependencies modified');
    }
    if (keyChanges.length === 0) {
      keyChanges.push('Code logic updated');
    }
    
    const risk = total > 200 ? 'Medium' : 'Low';
    const testing = diff.includes('test') ? '✅ Tests included' : '⚠️ Consider adding tests';
    
    return { type, size, additions, deletions, keyChanges, risk, testing };
  }
}

module.exports = BobAIExplainer;

